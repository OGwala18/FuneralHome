"""Premiums owed: what is overdue, what is coming up, and recording payments.

The schedule itself is generated by services/instalments.py when a member is
enrolled, and rolled forward by app/jobs/schedule_instalments.py. This router
is the office's view of it. Recording a payment is book-keeping only; there are
no bank or card details anywhere on this path.
"""

from __future__ import annotations

from datetime import date, datetime
from typing import Literal
from uuid import UUID

from fastapi import APIRouter, Depends, HTTPException, Query, status
from pydantic import BaseModel, ConfigDict, Field, field_validator

from ..auth import StaffUser, require_role, require_staff
from ..db import connection
from ..services import instalments
from ..services.staff import log_staff_event

router = APIRouter(prefix="/api/admin", tags=["admin"],
                   dependencies=[Depends(require_staff)])

# Same list as policy_payments.method and premium_instalments.paid_method.
PaymentMethod = Literal["debit_order", "stop_order", "eft", "cash",
                        "card", "easypay", "payat", "undecided"]


class Instalment(BaseModel):
    id: UUID
    policy_id: UUID
    due_date: date
    amount_cents: int
    currency: str
    status: str
    paid_at: datetime | None = None
    paid_amount_cents: int | None = None
    paid_method: str | None = None
    recorded_by: str | None = None
    notes: str | None = None


class OutstandingRow(BaseModel):
    instalment_id: UUID
    policy_id: UUID
    policy_number: str
    due_date: date
    amount_cents: int
    currency: str
    days_overdue: int
    main_member_id: UUID | None = None
    main_member_surname: str | None = None
    main_member_first_names: str | None = None
    main_member_phone: str | None = None


class PaymentIn(BaseModel):
    model_config = ConfigDict(str_strip_whitespace=True, extra="forbid")

    paid_on: date
    amount_cents: int = Field(ge=0, le=100_000_000)
    method: PaymentMethod
    notes: str | None = Field(default=None, max_length=500)

    @field_validator("paid_on")
    @classmethod
    def _not_future(cls, value: date) -> date:
        if value > date.today():
            raise ValueError("A payment cannot be recorded for a future date")
        return value


class WaiveIn(BaseModel):
    model_config = ConfigDict(str_strip_whitespace=True, extra="forbid")

    reason: str = Field(min_length=3, max_length=500)


@router.get("/instalments", response_model=list[OutstandingRow])
def outstanding(staff: StaffUser = Depends(require_staff),
                view: Literal["overdue", "upcoming"] = "overdue",
                days: int = Query(default=7, ge=1, le=90)) -> list[OutstandingRow]:
    """Overdue: due and unpaid before today. Upcoming: due today or in `days` days."""
    if view == "overdue":
        clause, order = "days_overdue > 0", "due_date asc"
    else:
        clause, order = "days_overdue <= 0 and due_date <= current_date + %(days)s", "due_date asc"

    with connection() as conn:
        rows = conn.execute(
            f"""
            select instalment_id, policy_id, policy_number, due_date, amount_cents, currency,
                   days_overdue, main_member_id, main_member_surname,
                   main_member_first_names, main_member_phone
              from instalments_outstanding
             where {clause}
             order by {order}, policy_number
             limit 500
            """,
            {"days": days},
        ).fetchall()
        log_staff_event(conn, staff.email, "instalments_viewed", None,
                        {"view": view, "rows": len(rows)})
    return [OutstandingRow(**r) for r in rows]


def _not_due(conn, instalment_id: UUID) -> HTTPException:
    exists = conn.execute(
        "select status from premium_instalments where id = %s and archived_at is null",
        (instalment_id,),
    ).fetchone()
    if exists is None:
        return HTTPException(status.HTTP_404_NOT_FOUND, "No such instalment.")
    return HTTPException(status.HTTP_409_CONFLICT,
                         f"This instalment is already {exists['status']}.")


@router.post("/instalments/{instalment_id}/payment", response_model=Instalment)
def record_payment(instalment_id: UUID, payload: PaymentIn,
                   staff: StaffUser = Depends(require_role("admin"))) -> Instalment:
    """Mark an instalment paid. The first payment on a pending policy activates it."""
    with connection() as conn:
        row = instalments.record_payment(
            conn, str(instalment_id), paid_on=payload.paid_on,
            amount_cents=payload.amount_cents, method=payload.method,
            notes=payload.notes, staff_email=staff.email,
        )
        if row is None:
            raise _not_due(conn, instalment_id)
        log_staff_event(conn, staff.email, "instalment_paid", str(instalment_id),
                        {"policy_id": str(row["policy_id"]), "method": payload.method})
    return Instalment(**row)


@router.post("/instalments/{instalment_id}/waive", response_model=Instalment)
def waive_instalment(instalment_id: UUID, payload: WaiveIn,
                     staff: StaffUser = Depends(require_role("admin"))) -> Instalment:
    with connection() as conn:
        row = instalments.waive(conn, str(instalment_id), reason=payload.reason,
                                staff_email=staff.email)
        if row is None:
            raise _not_due(conn, instalment_id)
        log_staff_event(conn, staff.email, "instalment_waived", str(instalment_id),
                        {"policy_id": str(row["policy_id"])})
    return Instalment(**row)
